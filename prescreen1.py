def api_get(path, params=None, retries=5):
    """REST call with rate-limit handling. Returns None for 404/409/422."""
    url = path if path.startswith("http") else f"https://api.github.com{path}"
    for attempt in range(retries):
        try:
            r = SESSION.get(url, params=params, timeout=30)
        except requests.RequestException:
            time.sleep(2 ** attempt)
            continue
        if r.status_code == 200:
            time.sleep(DELAY)
            return r.json()
        if r.status_code == 401:
            raise SystemExit("GitHub rejected the token (401 Bad credentials). Set a valid GITHUB_TOKEN.")
        if r.status_code in (403, 429):
            if r.headers.get("X-RateLimit-Remaining") == "0":
                wait = max(int(r.headers.get("X-RateLimit-Reset", 0)) - time.time(), 5) + 2
            else:
                wait = int(r.headers.get("Retry-After", 30))
            log(f"  rate limited, sleeping {int(wait)}s")
            time.sleep(min(wait, 3700))
            continue
        if r.status_code in (404, 409, 422):
            return None
        if r.status_code >= 500:
            time.sleep(2 ** attempt)
            continue
        r.raise_for_status()
    raise GitError(f"API failed: {path}")

def graphql(query, variables, retries=8):
    """GraphQL call used by BOTH discovery and the activity rule. Waits and retries on rate
    limits, timeouts and network drops; says what went wrong if it finally gives up."""
    last = "no response"
    for attempt in range(retries):
        try:
            r = SESSION.post(GQL_URL, json={"query": query, "variables": variables}, timeout=60)
        except requests.RequestException as exc:
            last = f"network error: {type(exc).__name__}"
            wait = min(15 * 2 ** attempt, 600)
            log(f"  {last}; retry in {wait}s")
            time.sleep(wait)
            continue
        if r.status_code == 401:
            raise SystemExit("GitHub rejected the token (401 Bad credentials). Set a valid GITHUB_TOKEN.")
        if r.status_code in (403, 429, 502, 503, 504):
            last = f"HTTP {r.status_code}: {r.text[:120]}"
            reset = r.headers.get("X-RateLimit-Reset")
            if r.headers.get("Retry-After"):
                wait = int(r.headers["Retry-After"]) + 5
            elif r.headers.get("X-RateLimit-Remaining") == "0" and reset:
                wait = max(int(reset) - int(time.time()), 5) + 5
            else:
                wait = min(60 * 2 ** attempt, 900)
            log(f"  {last}; retry in {wait}s")
            time.sleep(wait)
            continue
        r.raise_for_status()
        data = r.json()
        errs = data.get("errors") or []
        text = str(errs).lower()
        retryable = (any(e.get("type") == "RATE_LIMITED" for e in errs)
                     or "timeout" in text or "something went wrong" in text)
        if errs and retryable:
            last = f"GraphQL: {text[:120]}"
            log(f"  {last}; retry in 60s")
            time.sleep(60)
            continue
        errs = [e for e in errs if e.get("type") != "NOT_FOUND"]
        if errs:
            raise RuntimeError(errs)
        time.sleep(DELAY)
        return data
    raise GitError(f"GraphQL failed after retries. Last problem: {last}")


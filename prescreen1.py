ACTIVITY_QUERY = """
query($login: String!, $f1: DateTime!, $t1: DateTime!, $f2: DateTime!, $t2: DateTime!) {
  user(login: $login) {
    a: contributionsCollection(from: $f1, to: $t1) { totalCommitContributions }
    b: contributionsCollection(from: $f2, to: $t2) { totalCommitContributions }
  }
}
"""

def pre_commit_total(login):
    """Commits by the account in the pre window, across ALL repos and languages.
    GitHub allows at most one year per contributionsCollection, so the 24-month window is
    asked as two consecutive 365-day halves in ONE request. None if the user is not found."""
    mid = PRE_START + timedelta(days=365)
    variables = {"login": login,
                 "f1": iso(PRE_START), "t1": iso(mid - timedelta(seconds=1)),
                 "f2": iso(mid), "t2": iso(PRE_END)}
    data = graphql(ACTIVITY_QUERY, variables)
    user = (data.get("data") or {}).get("user")
    if not user:
        return None
    return user["a"]["totalCommitContributions"] + user["b"]["totalCommitContributions"]

def eligible_repos(login):
    """Owner repos that could hold qualifying pre-window code. Newest push first."""
    repos, page = [], 1
    while page <= 5:
        data = api_get(f"/users/{login}/repos",
                       {"type": "owner", "sort": "pushed", "per_page": 100, "page": page})
        if not data:
            break
        repos.extend(data)
        if len(data) < 100:
            break
        page += 1
    keep = [r for r in repos
            if not r["fork"] and not r["archived"] and not r.get("disabled")
            and 0 < r["size"] < MAX_REPO_KB and r.get("language") == REPO_LANGUAGE
            and (r.get("pushed_at") or "") >= iso(PRE_START)
            and not EXCLUDE_REPO.search(r["name"] + " " + (r.get("description") or ""))]
    return keep[:MAX_REPOS_CHECKED]

def repo_pre_commits(profile, repos):
    """Per repo, the user's commits in the pre window (all file types, max 100, so an upper
    bound on Python commits). Also collects the emails GitHub itself links to this login.
    Display names are never used to attribute commits."""
    login = profile["login"]
    emails = {f"{profile['id']}+{login}@users.noreply.github.com".lower(),
              f"{login}@users.noreply.github.com".lower()}
    counts = {}
    for r in repos:
        data = api_get(f"/repos/{r['full_name']}/commits",
                       {"author": login, "since": iso(PRE_START), "until": iso(PRE_END),
                        "per_page": 100}) or []
        mine = [c for c in data
                if ((c.get("author") or {}).get("login") or "").lower() == login.lower()]
        counts[r["full_name"]] = len(mine)
        for c in mine:
            e = ((c.get("commit") or {}).get("author") or {}).get("email")
            if e:
                emails.add(e.lower())
    return emails, counts

def clone(url, dest):
    """Bare clone with full history. A later fetch updates it."""
    if dest.exists():
        git(dest, "fetch", "--quiet", "--prune", "origin", "+refs/heads/*:refs/heads/*")
    else:
        r = run(["git", "clone", "--bare", "--quiet", url, str(dest)], timeout=CLONE_TIMEOUT)
        if r.returncode:
            raise GitError(r.stderr.strip()[:300])

def python_commits(repo):
    """Non-merge commits on HEAD that add or modify .py files."""
    out = git(repo, "log", "HEAD", "--no-merges", "--no-renames", "--diff-filter=AM",
              "--name-only", "--format=%x1e%H%x1f%aI%x1f%ae", "--", "*.py")
    commits = []
    for chunk in out.split("\x1e")[1:]:
        lines = chunk.splitlines()
        h, d, e = lines[0].split("\x1f")
        files = [l.strip() for l in lines[1:] if l.strip().endswith(".py")]
        if files:
            commits.append({"hash": h, "date": datetime.fromisoformat(d).astimezone(UTC),
                            "email": e.strip().lower(), "files": files})
    return commits

def snapshot_pre(repo_dir, emails):
    """Single-author rule and the user's pre-window activity in one repo. Author share is
    measured over Python commits UP TO THE END of the pre window. None if the repo is not
    single-author enough."""
    commits = [c for c in python_commits(repo_dir) if c["date"] <= PRE_END]
    if not commits:
        return None
    mine = [c for c in commits if c["email"] in emails]
    if len(mine) / len(commits) < MIN_AUTHOR_SHARE:
        return None
    latest, n, weeks = {}, 0, set()
    for c in mine:
        if not (PRE_START <= c["date"] <= PRE_END) or len(c["files"]) > BULK_THRESHOLD:
            continue
        files = [f for f in c["files"] if not EXCLUDE_PATH.search(f)]
        if not files:
            continue
        n += 1
        weeks.add(c["date"].strftime("%G-W%V"))
        for f in files:
            if f not in latest or c["date"] > latest[f][1]:
                latest[f] = (c["hash"], c["date"])
    return {"commits": n, "weeks": weeks, "files": {p: h for p, (h, _) in latest.items()}}

def blob(repo, commit, path):
    r = subprocess.run(["git", "-C", str(repo), "show", f"{commit}:{path}"],
                       capture_output=True, timeout=60)
    if r.returncode or len(r.stdout) > MAX_FILE_BYTES:
        return None
    return r.stdout.decode("utf-8", errors="replace")

def sloc_estimate(src):
    return sum(1 for l in src.splitlines() if l.strip() and not l.strip().startswith("#"))

def usable_files(repo_dir, files, login):
    """Keep only files that are Python 3 (ast.parse succeeds), not auto-generated and at least
    MIN_SLOC lines. Also returns the parse rate: the share of checked files that parsed, so
    Python 2 repos can be rejected. Random order, capped, so no repo dominates."""
    items = sorted(files.items())
    random.Random(login).shuffle(items)
    good, tried = {}, 0
    for path, commit in items[:MAX_FILES_CHECKED]:
        src = blob(repo_dir, commit, path)
        if not src or GENERATED_MARK.search("\n".join(src.splitlines()[:5])):
            continue
        if sloc_estimate(src) < MIN_SLOC:
            continue
        tried += 1
        try:
            ast.parse(src)
        except (SyntaxError, ValueError, RecursionError):
            continue
        good[path] = commit
    return good, (len(good) / tried if tried else 0.0)

LOG_FIELDS = ["uid", "login", "country", "gender", "outcome", "pre_commits_all",
              "repos_checked", "repos_used", "py_commits", "py_weeks", "py_files"]
MANIFEST_FIELDS = ["uid", "period", "repo", "path", "commit"]

def screen_user(login, cache, min_commits):
    """Rules in order of cost, stopping at the first failure.
    Returns (outcome, stats, manifest_rows, repos_used)."""
    stats = dict.fromkeys(["pre_commits_all", "repos_checked", "repos_used",
                           "py_commits", "py_weeks", "py_files"], "")
    total = pre_commit_total(login)
    if total is None:
        return "NOT_FOUND", stats, [], []
    stats["pre_commits_all"] = total
    if total < min_commits:
        return "PRE_FEW_COMMITS", stats, [], []
    profile = api_get(f"/users/{login}")
    if not profile or profile.get("type") != "User":
        return "NOT_USER", stats, [], []
    repos = eligible_repos(login)
    if not repos:
        return "NO_REPOS", stats, [], []
    emails, counts = repo_pre_commits(profile, repos)
    stats["repos_checked"] = len(repos)
    ranked = sorted((r for r in repos if counts[r["full_name"]] > 0),
                    key=lambda r: -counts[r["full_name"]])[:MAX_REPOS]
    if not ranked:
        return "NO_PRE_REPO_ACTIVITY", stats, [], []

    commits, weeks, rows, used = 0, set(), [], []
    for r in ranked:
        dest = cache / f"{r['full_name'].replace('/', '__')}.git"
        log(f"    cloning {r['name']}")
        try:
            clone(r["clone_url"], dest)
            snap = snapshot_pre(dest, emails)
            if not snap:
                continue
            good, rate = usable_files(dest, snap["files"], login)
            if rate < MIN_PARSE_RATE:
                log(f"    skip {r['name']}: only {rate:.0%} of files parse as Python 3")
                continue
        except (GitError, ValueError) as exc:
            log(f"    skip {r['name']}: {exc}")
            continue
        if not good:
            continue
        used.append(r["full_name"])
        commits += snap["commits"]
        weeks |= snap["weeks"]
        rows += [(r["full_name"], p, h) for p, h in good.items()]
    stats.update(repos_used=len(used), py_commits=commits,
                 py_weeks=len(weeks), py_files=len(rows))
    if len(used) < MIN_REPOS:
        return "PRE_NO_QUALIFYING_REPO", stats, [], []
    if commits < MIN_PY_COMMITS or len(weeks) < MIN_WEEKS or len(rows) < MIN_FILES:
        return "PRE_THIN_PYTHON", stats, [], []
    uid = uid_for(login)
    manifest = [{"uid": uid, "period": "pre", "repo": repo, "path": p, "commit": h}
                for repo, p, h in rows]
    return "OK", stats, manifest, used

def open_csv(path, fields):
    new = not path.exists() or path.stat().st_size == 0
    fh = open(path, "a", newline="", encoding="utf-8")
    w = csv.DictWriter(fh, fieldnames=fields)
    if new:
        w.writeheader()
    return fh, w

def cmd_screen(args):
    if not Path(args.candidates).exists():
        sys.exit(f"Candidate file not found: {args.candidates}\n"
                 "Run 'python prescreen1.py discover' first, or pass --candidates <full path>.")
    cache = Path(args.cache)
    cache.mkdir(parents=True, exist_ok=True)
    cands = [c for c in read_csv(args.candidates) if c["country"] in COUNTRIES]
    if args.country:
        cands = [c for c in cands if c["country"] == args.country]
    random.Random(args.seed).shuffle(cands)
    log_path = Path(args.log)
    done, ok = set(), defaultdict(int)
    if log_path.exists() and log_path.stat().st_size:
        for r in read_csv(log_path):
            done.add(r["login"])
            if r["outcome"] == "OK":
                ok[(r["country"], r["gender"])] += 1
    lf, lw = open_csv(log_path, LOG_FIELDS)
    mf, mw = open_csv(Path(args.manifest), MANIFEST_FIELDS)
    pf, pw = open_csv(Path(args.passed), PASSED_FIELDS)

    cells = {(c["country"], c["group"].strip().lower()) for c in cands}
    for c in cands:
        if all(ok[cell] >= args.target for cell in cells):
            break
        login, country, g = c["login"], c["country"], c["group"].strip().lower()
        if login in done or ok[(country, g)] >= args.target:
            continue
        status = " ".join(f"{k[0][:2]}-{k[1][:1]}:{ok[k]}" for k in sorted(cells))
        log(f"[{status} / {args.target}] {login} ({country}, {g})")
        try:
            outcome, stats, rows, used = screen_user(login, cache, args.min_commits)
        except SystemExit:
            raise
        except Exception as exc:
            outcome, stats, rows, used = f"ERROR:{type(exc).__name__}", {}, [], []
        log(f"   -> {outcome}")
        lw.writerow({"uid": uid_for(login), "login": login, "country": country,
                     "gender": g, "outcome": outcome, **stats})
        lf.flush()
        if outcome == "OK":
            mw.writerows(rows)
            mf.flush()
            pw.writerow({"uid": uid_for(login), "login": login, "country": country,
                         "gender": g, "pre_commits_all": stats["pre_commits_all"],
                         "repos_pre": ";".join(used)})
            pf.flush()
            ok[(country, g)] += 1
    log(f"Done. Pre-screen passes per (country, gender): {dict(ok)}")
    log("All files are PRIVATE.")


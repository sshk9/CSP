#!/usr/bin/env python3
"""metrics.py - compute file-level metrics for selected users, then aggregate.
Usage:
  python metrics.py run --quota 30 --max-files 40
  python metrics.py aggregate
Inputs: manifest.csv, selected_users.csv, repo_cache/.  Outputs: files_metrics.csv,
user_period.csv, metrics_skipped.csv, tool_versions.txt.
"""

import argparse, ast, csv, hashlib, json, math, random, re, subprocess, sys, tempfile
from collections import defaultdict
from importlib.metadata import version
from pathlib import Path

# CONFIG & NAMING------------------------------------------------------------------------
MAX_FILE_BYTES = 300_000
MIN_SLOC = 10
GENERATED_MARK = re.compile(r"auto-?generated|generated by|do not edit|@generated", re.I)
FORMATTER = re.compile(r"black|ruff|yapf|autopep8", re.I)
CONFIG_FILES = ("pyproject.toml", "ruff.toml", ".ruff.toml", ".pre-commit-config.yaml",
                "setup.cfg", "tox.ini")
NAN = float("nan")
FUNC = (ast.FunctionDef, ast.AsyncFunctionDef)

def mean(x):
    return sum(x) / len(x) if x else NAN

# ---- naming (Xu et al. 2.2). Precedence: single > UPPER > snake > Pascal > camel > lower.
# Leading/trailing underscores stripped; dunders, self, cls and "_" are skipped.
# endsWithDigits is an overlapping flag, not a category.
CATS = ("single", "upper", "snake", "pascal", "camel", "lower")

def name_category(n):
    s = n.strip("_")
    if not s:
        return None
    if len(s) == 1:
        return "single"
    if re.fullmatch(r"[A-Z][A-Z0-9_]*", s):
        return "upper"
    if "_" in s:
        return "snake" if re.fullmatch(r"[a-z0-9]+(?:_[a-z0-9]+)+", s) else "other"
    if re.fullmatch(r"[A-Z][A-Za-z0-9]*", s):
        return "pascal"
    if re.fullmatch(r"[a-z][a-z0-9]*[A-Z][A-Za-z0-9]*", s):
        return "camel"
    if re.fullmatch(r"[a-z][a-z0-9]*", s):
        return "lower"
    return "other"

def naming_metrics(tree, path):
    groups = {"var": set(), "func": set(), "file": {Path(path).stem}}
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            groups["var"].add(node.id)
        elif isinstance(node, ast.arg):
            groups["var"].add(node.arg)
        elif isinstance(node, FUNC):
            groups["func"].add(node.name)
    out = {}
    for g, names in groups.items():
        names = [n for n in names
                 if not (n.startswith("__") and n.endswith("__")) and n not in ("self", "cls")
                 and n.strip("_")]
        total = len(names)
        cats = [name_category(n) for n in names]
        for c in CATS:
            out[f"{g}_{c}"] = cats.count(c) / total if total else NAN
        out[f"{g}_digit_end"] = sum(bool(re.search(r"\d$", n)) for n in names) / total if total else NAN
        out[f"{g}_len_mean"] = mean([len(n) for n in names])
    return out

# STRUCTURE, NESTING, COMPLEXITY, HALSTEAD, MI ------------------------------------------
CONTROL = tuple(getattr(ast, n) for n in
                ("If", "For", "While", "Try", "With", "AsyncFor", "AsyncWith", "Match")
                if hasattr(ast, n))

def max_depth(node, d=0):
    best = d
    for ch in ast.iter_child_nodes(node):
        best = max(best, max_depth(ch, d + 1 if isinstance(ch, CONTROL) else d))
    return best

def docstring_lines(tree):
    n = 0
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef) + FUNC):
            b = node.body
            if (b and isinstance(b[0], ast.Expr) and isinstance(b[0].value, ast.Constant)
                    and isinstance(b[0].value.value, str)):
                n += b[0].end_lineno - b[0].lineno + 1
    return n

def structure_metrics(src, tree):
    from radon.raw import analyze
    raw = analyze(src)
    methods, funcs, classes = set(), [], 0
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            classes += 1
            methods.update(ch for ch in node.body if isinstance(ch, FUNC))
        elif isinstance(node, FUNC):
            funcs.append(node)
    lens = [f.end_lineno - f.lineno + 1 for f in funcs]
    return {
        "loc": raw.loc, "sloc": raw.sloc, "blank": raw.blank,
        "comment_lines": raw.comments, "docstring_lines": docstring_lines(tree),
        "n_functions": len(funcs) - len(methods), "n_methods": len(methods),
        "n_classes": classes, "avg_function_len": mean(lens),   # NaN if no functions
        "max_nesting": max_depth(tree),
        "comment_ratio": raw.comments / max(raw.loc, 1),
        "docstring_ratio": docstring_lines(tree) / max(raw.sloc, 1),
    }

def flat_functions(blocks):
    for b in blocks:
        if hasattr(b, "methods"):                      # radon Class: use its methods only
            yield from flat_functions(b.methods)
            yield from flat_functions(getattr(b, "inner_classes", []))
        else:
            yield b

def complexity_metrics(src, m):
    from radon.complexity import cc_visit
    from radon.metrics import h_visit
    cc = [b.complexity for b in flat_functions(cc_visit(src))]
    h = h_visit(src).total
    cc_total = max(sum(cc), 1)
    out = {"cc_mean": mean(cc), "cc_max": max(cc) if cc else NAN, "cc_total": cc_total,
           "h_vocabulary": h.vocabulary, "h_length": h.length, "h_volume": h.volume,
           "h_difficulty": h.difficulty, "h_effort": h.effort, "h_time": h.time,
           "h_bugs": h.bugs, "mi_std": NAN, "mi_custom": NAN}
    if h.volume > 0 and m["sloc"] > 0:
        # Xu et al.: MI = 171 - 5.2 ln V - 0.23 CC - 16.2 ln S  (raw, not rescaled to 0-100)
        std = 171 - 5.2 * math.log(h.volume) - 0.23 * cc_total - 16.2 * math.log(m["sloc"])
        out["mi_std"] = std
        out["mi_custom"] = std + 50 * math.sin(math.sqrt(2.4 * m["comment_ratio"]))
    return out

def file_metrics(src, tree, path):
    m = structure_metrics(src, tree)
    m.update(complexity_metrics(src, m))
    m.update(naming_metrics(tree, path))
    return m

# LINTING -------------------------------------------------------------------------------
def lint_files(srcs):
    """srcs: {int_key: source}. Returns {key: counts by pylint type + pycodestyle}."""
    import pycodestyle
    out = {k: defaultdict(int) for k in srcs}
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        names = {}
        for k, s in srcs.items():
            n = f"m{k:05d}.py"
            (tmp / n).write_text(s, encoding="utf-8")
            names[n] = k
        rc = tmp / "empty.rc"
        rc.write_text("[MASTER]\n")
        paths = [str(tmp / n) for n in names]
        for i in range(0, len(paths), 50):
            r = subprocess.run(
                [sys.executable, "-m", "pylint", "--rcfile", str(rc), "--output-format=json",
                 "--score=n", "-j", "0", "--persistent=n",
                 "--disable=import-error,no-name-in-module", *paths[i:i + 50]],
                capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=3600)
            if not r.stdout.strip():     # pylint prints [] when clean; empty = crash
                raise RuntimeError("pylint failed: " + r.stderr[:200])
            for msg in json.loads(r.stdout):
                key = names.get(Path(msg["path"]).name)
                if key is not None:
                    out[key][msg["type"]] += 1
        for n, k in names.items():       # fresh Checker per file (no cumulative counts)
            out[k]["pycodestyle"] = pycodestyle.Checker(str(tmp / n), quiet=1).check_all()
    return out

# RUNNER, AGGREGATION, CLI --------------------------------------------------------------
PROBE = "def f(x):\n    return x\n"
ID_COLS = ["uid", "presentation", "period", "repo_hash", "file_hash"]
LINT_COLS = ["pylint_conv_per_ksloc", "pylint_warn_per_ksloc", "pylint_refactor_per_ksloc",
             "pylint_error_per_ksloc", "pycodestyle_per_ksloc"]
FIELDS = (["uid", "presentation", "period", "repo_hash", "file_hash", "formatter_cfg"]
          + list(file_metrics(PROBE, ast.parse(PROBE), "a.py")) + LINT_COLS)

def blob(repo, commit, path):
    r = subprocess.run(["git", "-C", str(repo), "show", f"{commit}:{path}"],
                       capture_output=True, timeout=60)
    if r.returncode or len(r.stdout) > MAX_FILE_BYTES:
        return None
    return r.stdout.decode("utf-8", errors="replace")

_fmt = {}
def uses_formatter(repo, commit):
    key = (str(repo), commit)
    if key not in _fmt:
        _fmt[key] = int(any((t := blob(repo, commit, f)) and FORMATTER.search(t)
                            for f in CONFIG_FILES))
    return _fmt[key]

def h8(s):
    return hashlib.sha256(s.encode()).hexdigest()[:8]

def process_user(uid, group, rows, cache, max_files, seed):
    rnd = random.Random(f"{seed}{uid}")
    out = []
    for period in ("pre", "post"):
        picks = sorted((r for r in rows if r["period"] == period), key=lambda r: (r["repo"], r["path"]))
        rnd.shuffle(picks)                      # random file choice, never by metric value
        srcs, feats = {}, {}
        for r in picks:
            if len(srcs) >= max_files:
                break
            repo = cache / f"{r['repo'].replace('/', '__')}.git"
            src = blob(repo, r["commit"], r["path"])
            if not src or GENERATED_MARK.search("\n".join(src.splitlines()[:5])):
                continue
            try:
                f = file_metrics(src, ast.parse(src), r["path"])
            except Exception:                   # Py2 code, syntax errors, odd files
                continue
            if f["sloc"] < MIN_SLOC:
                continue
            k = len(srcs)
            f.update(uid=uid, presentation=group, period=period, repo_hash=h8(r["repo"]),
                     file_hash=h8(r["repo"] + r["path"]),
                     formatter_cfg=uses_formatter(repo, r["commit"]))
            srcs[k], feats[k] = src, f
        if len(srcs) < 3:
            return None, f"FEW_FILES_{period.upper()}"
        lint = lint_files(srcs)
        for k, f in feats.items():
            ks = max(f["sloc"], 1) / 1000
            l = lint[k]
            f["pylint_conv_per_ksloc"] = l["convention"] / ks
            f["pylint_warn_per_ksloc"] = l["warning"] / ks
            f["pylint_refactor_per_ksloc"] = l["refactor"] / ks
            f["pylint_error_per_ksloc"] = (l["error"] + l["fatal"]) / ks
            f["pycodestyle_per_ksloc"] = l["pycodestyle"] / ks
            out.append(f)
    return out, "OK"

def cmd_run(args):
    cache = Path(args.cache)
    manifest = defaultdict(list)
    for r in csv.DictReader(open(args.manifest, encoding="utf-8")):
        manifest[r["uid"]].append(r)
    selected = list(csv.DictReader(open(args.selected, encoding="utf-8")))
    with open("tool_versions.txt", "w") as f:
        f.write(f"python {sys.version.split()[0]}\n" + "".join(
            f"{p} {version(p)}\n" for p in ("pylint", "pycodestyle", "radon")))
    out_path, skip_path = Path(args.out), Path("metrics_skipped.csv")
    done, ok = set(), defaultdict(int)
    if out_path.exists():
        seen = {}
        for r in csv.DictReader(open(out_path, encoding="utf-8")):
            seen[r["uid"]] = r["presentation"]
        done |= set(seen)
        for g in seen.values():
            ok[g] += 1
    if skip_path.exists():
        done |= {r["uid"] for r in csv.DictReader(open(skip_path, encoding="utf-8"))}
    new = not out_path.exists()
    fh = open(out_path, "a", newline="", encoding="utf-8")
    w = csv.DictWriter(fh, fieldnames=FIELDS, extrasaction="ignore")
    if new:
        w.writeheader()
    sk = open(skip_path, "a", newline="", encoding="utf-8")
    sw = csv.DictWriter(sk, fieldnames=["uid", "reason"])
    if sk.tell() == 0:
        sw.writeheader()
    for s in selected:
        uid, g = s["uid"], s["presentation"]
        if uid in done or ok[g] >= args.quota or uid not in manifest:
            continue
        print(f"[{g} {ok[g]}/{args.quota}] {uid}", flush=True)
        try:
            rows, status = process_user(uid, g, manifest[uid], cache, args.max_files, args.seed)
        except Exception as exc:
            rows, status = None, f"ERROR:{type(exc).__name__}"
        print(f"   -> {status}", flush=True)
        if rows:
            w.writerows(rows); fh.flush(); ok[g] += 1
        else:
            sw.writerow({"uid": uid, "reason": status}); sk.flush()
    print(f"Done. Included per group: {dict(ok)}")

def cmd_aggregate(args):
    import pandas as pd
    df = pd.read_csv(args.files)
    num = [c for c in df.columns if c not in ID_COLS]
    g = df.groupby(["uid", "presentation", "period"])
    agg = g[num].mean()                          # NaN-skipping mean over files
    agg["n_files"] = g.size()
    agg["total_sloc"] = g["sloc"].sum()
    agg["n_repos"] = g["repo_hash"].nunique()
    agg = agg.reset_index()
    agg.to_csv(args.out, index=False)
    print(agg.groupby(["presentation", "period"]).agg(users=("uid", "nunique"),
          files=("n_files", "sum")))
    print(f"Wrote {args.out}")

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--manifest", default="manifest.csv")
    r.add_argument("--selected", default="selected_users.csv")
    r.add_argument("--cache", default="repo_cache")
    r.add_argument("--out", default="files_metrics.csv")
    r.add_argument("--quota", type=int, default=30)
    r.add_argument("--max-files", type=int, default=40)
    r.add_argument("--seed", type=int, default=42)
    r.set_defaults(fn=cmd_run)
    a = sub.add_parser("aggregate")
    a.add_argument("--files", default="files_metrics.csv")
    a.add_argument("--out", default="user_period.csv")
    a.set_defaults(fn=cmd_aggregate)
    args = ap.parse_args()
    args.fn(args)

if __name__ == "__main__":
    main()
